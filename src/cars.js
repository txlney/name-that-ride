// Photos live in src/assets/cars/<make>/<year>-<model>.webp (lowercase, spaces -> "-", hyphens -> "=").
// Drop in a .jpg/.png and run `npm run optimize-images` to convert it; unconverted photos still work meanwhile.
// import.meta.glob lets Vite bundle them and hand back a real URL for each.
const photos = import.meta.glob('./assets/cars/*/*.{webp,jpg,jpeg,png}', { eager: true, query: '?url', import: 'default' })
const PHOTO_EXTENSIONS = ['webp', 'jpg', 'jpeg', 'png']

function photoPath({ year, make, model }) {
    const makeSlug = make.toLowerCase().replace(/ /g, '-')
    const modelSlug = model.toLowerCase().replace(/-/g, '=').replace(/ /g, '-')
    return `./assets/cars/${makeSlug}/${year}-${modelSlug}`
}

function findPhoto(car) {
    const base = photoPath(car)
    for (const ext of PHOTO_EXTENSIONS) {
        if (photos[`${base}.${ext}`]) return photos[`${base}.${ext}`]
    }
}

const cars = rawCars
    .map(car => {
        const label = `${car.year} ${car.make} ${car.model}`
        const image = findPhoto(car)
        if (!image && import.meta.env.DEV) console.warn(`No photo for ${label}, expected ${photoPath(car)}.webp`)
        return { ...car, label, searchText: label.toLowerCase(), image }
    })
    .sort((a, b) =>
        a.make.localeCompare(b.make) ||
        b.year.localeCompare(a.year) ||
        a.model.localeCompare(b.model)
    )

export default cars

